-- Bucket privado para fotos e vídeos enviados no formulário.
insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values ('lead-media', 'lead-media', false, 20971520, array['image/*','video/*']::text[])
on conflict (id) do update set
  public = false,
  file_size_limit = excluded.file_size_limit,
  allowed_mime_types = excluded.allowed_mime_types;

-- Visitantes só fazem upload em um caminho público aleatório; não recebem permissão de leitura.
drop policy if exists "public can upload lead media" on storage.objects;
create policy "public can upload lead media"
on storage.objects for insert
to anon, authenticated
with check (bucket_id = 'lead-media' and name like 'public/%');

-- Admins podem ler e excluir as mídias.
drop policy if exists "admins can read lead media" on storage.objects;
create policy "admins can read lead media"
on storage.objects for select
to authenticated
using (
  bucket_id = 'lead-media'
  and exists (select 1 from public.admin_profiles ap where ap.user_id = (select auth.uid()) and ap.active = true)
);

drop policy if exists "admins can delete lead media" on storage.objects;
create policy "admins can delete lead media"
on storage.objects for delete
to authenticated
using (
  bucket_id = 'lead-media'
  and exists (select 1 from public.admin_profiles ap where ap.user_id = (select auth.uid()) and ap.active = true)
);
