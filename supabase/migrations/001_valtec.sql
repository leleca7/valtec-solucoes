-- Perfil de admin: cada usuário autenticado só consegue enxergar o próprio registro.
drop policy if exists "admin can read own profile" on public.admin_profiles;
create policy "admin can read own profile"
on public.admin_profiles for select
to authenticated
using ((select auth.uid()) = user_id and active = true);

-- Bairros podem ser consultados pelo site público.
drop policy if exists "public can read active service areas" on public.service_areas;
create policy "public can read active service areas"
on public.service_areas for select
to anon, authenticated
using (active = true);

-- Leads: visitante pode criar, mas não ler. O status inicial é sempre 'novo'.
drop policy if exists "public can create leads" on public.leads;
create policy "public can create leads"
on public.leads for insert
to anon, authenticated
with check (status = 'novo');

-- Admins podem operar leads.
drop policy if exists "admins can read leads" on public.leads;
create policy "admins can read leads"
on public.leads for select
to authenticated
using (exists (
  select 1 from public.admin_profiles ap
  where ap.user_id = (select auth.uid()) and ap.active = true
));

drop policy if exists "admins can update leads" on public.leads;
create policy "admins can update leads"
on public.leads for update
to authenticated
using (exists (
  select 1 from public.admin_profiles ap
  where ap.user_id = (select auth.uid()) and ap.active = true
))
with check (exists (
  select 1 from public.admin_profiles ap
  where ap.user_id = (select auth.uid()) and ap.active = true
));

drop policy if exists "admins can delete leads" on public.leads;
create policy "admins can delete leads"
on public.leads for delete
to authenticated
using (exists (
  select 1 from public.admin_profiles ap
  where ap.user_id = (select auth.uid()) and ap.active = true
));

-- Métricas: qualquer visitante pode registrar eventos, só admin pode ler.
drop policy if exists "public can create analytics events" on public.analytics_events;
create policy "public can create analytics events"
on public.analytics_events for insert
to anon, authenticated
with check (char_length(event_name) between 1 and 80);

