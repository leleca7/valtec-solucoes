-- Valtec Soluções — schema inicial
-- Compatível com o modelo atual do Supabase em que novas tabelas podem exigir GRANT explícito para a Data API.

create table if not exists public.admin_profiles (
  user_id uuid primary key references auth.users(id) on delete cascade,
  display_name text,
  active boolean not null default true,
  created_at timestamptz not null default now()
);

create table if not exists public.service_areas (
  id bigint generated by default as identity primary key,
  neighborhood text not null unique,
  priority text not null default 'principal' check (priority in ('principal', 'consulta')),
  active boolean not null default true,
  created_at timestamptz not null default now()
);

create table if not exists public.leads (
  id uuid primary key default gen_random_uuid(),
  customer_name text not null,
  phone text not null,
  equipment text not null,
  problems text[] not null default '{}',
  description text,
  neighborhood text not null,
  address text,
  reference_point text,
  media_path text,
  source text not null default 'site',
  status text not null default 'novo' check (status in ('novo','contatado','agendado','concluido','arquivado')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists leads_created_at_idx on public.leads(created_at desc);
create index if not exists leads_neighborhood_idx on public.leads(neighborhood);
create index if not exists leads_equipment_idx on public.leads(equipment);

create table if not exists public.analytics_events (
  id bigint generated by default as identity primary key,
  event_name text not null,
  path text,
  neighborhood text,
  equipment text,
  problem text,
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

create index if not exists analytics_events_name_created_idx on public.analytics_events(event_name, created_at desc);
create index if not exists analytics_events_neighborhood_idx on public.analytics_events(neighborhood) where neighborhood is not null;

create table if not exists public.clients (
  id uuid primary key default gen_random_uuid(),
  name text not null,
  phone text not null,
  neighborhood text,
  address text,
  notes text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists clients_phone_idx on public.clients(phone);

create table if not exists public.service_orders (
  id uuid primary key default gen_random_uuid(),
  client_id uuid references public.clients(id) on delete set null,
  lead_id uuid references public.leads(id) on delete set null,
  equipment text not null,
  problem text,
  service_description text,
  status text not null default 'aberto' check (status in ('aberto','agendado','em_execucao','concluido','cancelado')),
  scheduled_for timestamptz,
  completed_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.quotes (
  id uuid primary key default gen_random_uuid(),
  client_id uuid references public.clients(id) on delete set null,
  lead_id uuid references public.leads(id) on delete set null,
  service_order_id uuid references public.service_orders(id) on delete set null,
  title text not null default 'Orçamento Valtec',
  parts_total numeric(12,2) not null default 0,
  labor_amount numeric(12,2) not null default 0,
  original_total numeric(12,2) not null default 0,
  negotiated_total numeric(12,2),
  status text not null default 'rascunho' check (status in ('rascunho','enviado','aprovado','recusado','cancelado')),
  payment_notes text not null default 'As peças são pagas antecipadamente para a compra dos materiais. A mão de obra pode ser paga após a execução ou antecipadamente, se o cliente preferir.',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.quote_items (
  id uuid primary key default gen_random_uuid(),
  quote_id uuid not null references public.quotes(id) on delete cascade,
  description text not null,
  quantity numeric(10,2) not null default 1 check (quantity > 0),
  unit_price numeric(12,2) not null default 0 check (unit_price >= 0),
  created_at timestamptz not null default now()
);

create index if not exists quote_items_quote_id_idx on public.quote_items(quote_id);

